skip = {"nome", "marcas de produtos", "pesquise pelo nome da marca", "183110"}
vistos = set()
out = []
for n in BRUTO.splitlines():
    n = n.strip()
    if not n or n.lower() in skip:
        continue
    k = n.casefold()
    if k in vistos:
        continue
    vistos.add(k)
    out.append(n)

linhas = ["export const MARCAS_CATALOGO = ["]
for n in out:
    linhas.append(f"    {n!r},")
linhas += [
    "];",
    "",
    "export function nomesDeArquivoMarcas(texto) {",
    "    const linhas = String(texto || \"\").split(/\\r?\\n/);",
    "    const vistos = new Set();",
    "    const saida = [];",
    "    linhas.forEach((linha, idx) => {",
    "        const bruto = linha.trim();",
    "        if (!bruto) {",
    "            return;",
    "        }",
    "        const partes = bruto.split(/[;,\\t]/).map((p) => p.trim()).filter(Boolean);",
    "        if (idx === 0 && /^(nome|marca|descri[cç][aã]o)$/i.test(partes[0] || \"\")) {",
    "            return;",
    "        }",
    "        const nome = partes[0];",
    "        if (!nome) {",
    "            return;",
    "        }",
    "        const chave = nome.toLocaleLowerCase(\"pt-BR\");",
    "        if (vistos.has(chave)) {",
    "            return;",
    "        }",
    "        vistos.add(chave);",
    "        saida.push(nome);",
    "    });",
    "    return saida;",
    "}",
    "",
]

destino = Path(r"C:/Projetos/ERP-TemDeTudo/frontend/src/constants/marcasCatalogo.js")
destino.write_text("\n".join(linhas), encoding="utf-8")
print(len(out), str(destino))
